"""Generate docs/src/content/docs/reference/tools.md from the live tool definitions.

Run with:  uv run python scripts/gen_tool_reference.py
CI fails if the committed file differs from the generated one.
"""

from __future__ import annotations

import asyncio
import inspect
from pathlib import Path

from uv_mcp.config import ALL_TOOLSETS, Settings
from uv_mcp.registry import REGISTRY
from uv_mcp.server import create_server

OUT = Path(__file__).resolve().parent.parent / "docs" / "src" / "content" / "docs" / "reference" / "tools.md"

TOOLSET_TITLES = {
    None: ("Core", "Always available, whatever toolsets are enabled."),
    "diagnostics": ("Diagnostics", "Understand and fix a project without guessing."),
    "project": ("Project", "The uv project workflow: `pyproject.toml` + `uv.lock` + `.venv`."),
    "python": ("Python versions", "Install, find and pin interpreters."),
    "pip": ("pip interface", "Environment-level package management for plain virtualenvs and requirements files."),
    "venv": ("Virtual environments", ""),
    "tool": ("Tools (uvx)", "Run or install Python command-line tools in isolated environments."),
    "build": ("Packaging", "Build and publish distributions."),
    "cache": ("Cache", ""),
    "auth": ("Authentication", "Credentials for private package indexes."),
    "self": ("uv itself", ""),
}


def _type(schema: dict) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema:
        return " \\| ".join(_type(s) for s in schema["anyOf"] if s.get("type") != "null")
    kind = schema.get("type", "any")
    if kind == "array":
        return f"list[{_type(schema.get('items', {}))}]"
    if kind == "object":
        return "object"
    return {"string": "string", "boolean": "bool", "integer": "int", "number": "number"}.get(kind, kind)


def _default(schema: dict, required: bool) -> str:
    if required:
        return "**required**"
    if "default" in schema:
        value = schema["default"]
        if value is None:
            return ""
        return f"`{str(value).lower() if isinstance(value, bool) else value}`"
    return ""


def _badges(name: str) -> str:
    spec = REGISTRY[name]
    badges = []
    if spec.read_only:
        badges.append("read-only")
    elif spec.destructive:
        badges.append("destructive")
    else:
        badges.append("writes")
    if spec.idempotent:
        badges.append("idempotent")
    if spec.open_world:
        badges.append("network")
    return " · ".join(badges)


async def render() -> str:
    mcp = create_server(Settings(workspace_root=Path.cwd(), toolsets=frozenset(ALL_TOOLSETS)))
    tools = {t.name: t for t in await mcp.list_tools()}
    lines = [
        "---",
        "title: Tool reference",
        "description: Every uv-mcp tool, its parameters and its safety annotations.",
        "---",
        "",
        "<!-- Generated by scripts/gen_tool_reference.py. Do not edit by hand. -->",
        "",
        f"uv-mcp exposes **{len(tools)} tools**. Names mirror the uv CLI, so `uv pip list` is `uv_pip_list`.",
        "Every tool that runs uv returns the same envelope (`success`, `exit_code`, `command`, `cwd`, `stdout`,",
        "`stderr`, `duration_seconds`, `timed_out`, `truncated`, `hint`), plus parsed fields where noted.",
        "",
        "Badges reflect the MCP tool annotations clients use to decide when to ask for confirmation:",
        "**read-only** tools never change anything, **destructive** tools can delete or overwrite state or run",
        "arbitrary code, **network** tools may contact package indexes. In read-only mode only read-only tools",
        "are registered.",
        "",
        "Rarely used uv flags are not modelled as parameters: pass them through `extra_args`, for example",
        '`extra_args: ["--no-build-isolation"]`. Commands with no dedicated tool are available through `uv_command`.',
        "",
    ]
    order = [None, "diagnostics", *ALL_TOOLSETS]
    seen: set[str | None] = set()
    for toolset in order:
        if toolset in seen:
            continue
        seen.add(toolset)
        names = [n for n, s in REGISTRY.items() if s.toolset == toolset]
        if not names:
            continue
        title, blurb = TOOLSET_TITLES[toolset]
        lines.append(f"## {title}")
        lines.append("")
        if toolset:
            lines.append(f"Toolset: `{toolset}`. {blurb}".rstrip())
        else:
            lines.append(blurb)
        lines.append("")
        for name in names:
            tool = tools[name]
            lines.append(f"### `{name}`")
            lines.append("")
            lines.append(f"*{_badges(name)}*")
            lines.append("")
            lines.append(inspect.cleandoc(tool.description or ""))
            lines.append("")
            props = tool.parameters.get("properties", {})
            required = set(tool.parameters.get("required", []))
            if props:
                lines.append("| Parameter | Type | Default | Description |")
                lines.append("|---|---|---|---|")
                for pname, pschema in props.items():
                    desc = (pschema.get("description") or "").replace("|", "\\|")
                    lines.append(f"| `{pname}` | {_type(pschema)} | {_default(pschema, pname in required)} | {desc} |")
                lines.append("")
            else:
                lines.append("No parameters.")
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUT.write_text(asyncio.run(render()), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
